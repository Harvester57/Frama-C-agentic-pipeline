#!/bin/sh
# Issue 25: [Kernel] offsetof(T, m[i]) with a non-constant index i (GCC and
# Clang extension) aborts the parsing.
#
# Images: framac-master-audit:3dff90f (master 3dff90fc70, before),
#         framac-analysis:fc34 (34.0~beta, same output), and the master image
#         with ../patches/25-kernel-offsetof-non-constant-index.patch built and
#         installed (after). The struct offsets assume x86_64 (the default
#         machdep).
# Command, from this directory:
#   docker run --rm -v "$PWD:/w" -w /w --entrypoint sh <image> \
#     25-kernel-offsetof-non-constant-index.sh
#
# Output before (master 3dff90fc70; 34.0~beta prints the same):
#   --- gcc: compiles and runs, exit 0
#   --- frama-c -print
#   [kernel] 25-kernel-offsetof-non-constant-index.c:17: User Error:
#     Unable to compute offset .args[i] in type struct s: Index is not constant
#   [kernel] 25-kernel-offsetof-non-constant-index.c:25: User Error:
#     Unable to compute offset .inner[i].v[j] in type struct s: Index is not constant
#   RESULT: bug present (parsing aborted)
#
# Output after:
#   --- gcc: compiles and runs, exit 0
#   --- frama-c -print
#     __retres = 128UL + (unsigned long)i * 8UL;
#     __retres = (16UL + (unsigned long)i * 40UL) + (unsigned long)j * 8UL;
#   --- Eva (-warn-invalid-pointer): 0 alarms generated by the analysis.
#   --- WP (-wp-rte, Alt-Ergo): [wp] Proved goals:   13 / 13
#   RESULT: fixed
set -u
src=25-kernel-offsetof-non-constant-index.c
tmp=${TMPDIR:-/tmp}/repro25.$$
mkdir -p "$tmp"
if command -v gcc > /dev/null 2>&1; then
  if gcc -o "$tmp/a.out" "$src" && "$tmp/a.out"
  then echo "--- gcc: compiles and runs, exit 0"
  else echo "--- gcc: FAILED"
  fi
fi
echo "--- frama-c -print"
if ! frama-c -no-unicode "$src" -print -ocode "$tmp/out.c" > "$tmp/fc.log" 2>&1
then
  grep -A1 'User Error' "$tmp/fc.log" | grep -v -e '^--$' -e 'stopping on' \
    -e 'kernel-msg-key'
  rm -rf "$tmp"
  echo "RESULT: bug present (parsing aborted)"; exit 1
fi
grep '__retres = .*UL' "$tmp/out.c"
eva=$(frama-c -no-unicode "$src" -eva -warn-invalid-pointer 2>&1 \
        | grep 'alarms generated' | sed 's/^ *//')
echo "--- Eva (-warn-invalid-pointer): $eva"
if command -v alt-ergo > /dev/null 2>&1; then
  wp=$(frama-c -no-unicode "$src" -wp -wp-rte -wp-prover alt-ergo \
         -wp-timeout 10 -wp-cache none 2>&1 | grep 'Proved goals')
  echo "--- WP (-wp-rte, Alt-Ergo): $wp"
fi
rm -rf "$tmp"
echo "RESULT: fixed"
