#!/bin/sh
# Issue 74: [Libc] getpwnam_r/getpwuid_r and getut*_r assign result pointer
# from &__fc_pwd / &__fc_utmp instead of the caller struct pointer.
#
# Images: framac-master-audit:189053d (master 189053d4a2) and
#         framac-analysis:latest (34.0~beta); same "before" output on both.
# Command, from this directory:
#   docker run --rm -v "$PWD:/w" -w /w --entrypoint sh <image> \
#     74-libc-reentrant-result-pointer-assigns.sh
#
# Output before (master 189053d4a2; 34.0~beta prints the same), exit 1:
#   pwd_and_utmp_r: FAIL ( Assertions 0 valid 0 unknown 0 invalid 0 total;  6 alarms generated by the analysis:)
#   RESULT: bug present (1 of 1 checks fail)
#
# Output after (master 189053d4a2 with
# patches/74-libc-reentrant-result-pointer-assigns.patch installed), exit 0:
#   pwd_and_utmp_r: ok (5 valid assertions; 0 alarms)
#   RESULT: fixed
set -u
tmp=${TMPDIR:-/tmp}/repro74.$$
mkdir -p "$tmp"
failed=0
n=1

frama-c -no-unicode -eva \
  74-libc-reentrant-result-pointer-assigns.c > "$tmp/eva.log" 2>&1
rc=$?

if [ "$rc" = 0 ] \
   && grep -q 'Assertions[[:space:]]*5 valid[[:space:]]*0 unknown[[:space:]]*0 invalid[[:space:]]*5 total' "$tmp/eva.log" \
   && grep -q '0 alarms generated by the analysis\.' "$tmp/eva.log" \
   && ! grep -q 'garbled mix of &{__fc_utmp}' "$tmp/eva.log"; then
  echo "pwd_and_utmp_r: ok (5 valid assertions; 0 alarms)"
else
  asserts=$(grep -m1 'Assertions' "$tmp/eva.log" | tr -s ' ')
  alarms=$(grep -m1 'alarms generated by the analysis' "$tmp/eva.log" | tr -s ' ')
  echo "pwd_and_utmp_r: FAIL (${asserts:-no assertions}; ${alarms:-rc=$rc})"
  failed=$((failed + 1))
fi

rm -rf "$tmp"
if [ "$failed" = 0 ]; then
  echo "RESULT: fixed"
  exit 0
else
  echo "RESULT: bug present ($failed of $n checks fail)"
  exit 1
fi
