def test_keep_going_skips_case_280(tmp_path):
    crash = tmp_path / "crash-a"
    crash.write_bytes(_case_280() + b"\x00")
    calls: list[dict] = []
    masks: list[int] = []

    def campaign(binary, seconds, fork, *, extra_env=None):
        calls.append({"fork": fork, "env": extra_env})
        arts = (
            [{"artifact": str(crash), "kind": "crash", "sha256": "a", "fingerprint": "fp"}] if len(calls) == 1 else []
        )
        return {"status": "crash_found" if arts else "clean", "returncode": 1 if arts else 0, "artifacts": arts}

    def rebuild(mask):
        masks.append(mask)
        return Path("bin2"), {}

    res = R.run_campaign_rounds(
        Path("bin"), 600, campaign=campaign, rebuild=rebuild, n_cases=300, selector="identity16"
    )
    kg = res["keep_going"]
    assert kg["rounds"][0]["crashed_cases"] == [280] and kg["skipped_cases"] == [280]
    assert kg["dispatch_selector"] == "identity16"
    assert masks == [1 << 280]
    assert (
        R.dispatch_skip_cppflags(masks[0]) == "-DFRAMAC_FUZZ_SKIP_CASES=0x0ULL -DFRAMAC_FUZZ_SKIP_CASES_4=0x1000000ULL"
    )
    # At run time the round skips case 280 through the environment instead.
    calls.clear()
    res = R.run_campaign_rounds(
        Path("bin"),
        600,
        campaign=campaign,
        rebuild=rebuild,
        n_cases=300,
        selector="identity16",
        runtime_skip=True,
    )
    assert res["keep_going"]["skipped_cases"] == [280]
    assert calls[1]["env"] == {"FRAMAC_FUZZ_SKIP_CASES": "280"}


def _wide_api_cases() -> list[dict]:
    return [
        {
            "selector": i,
            "kind": "single",
            "entry": "rec_parse" if i == 280 else "rec_put",
            "calls": ["rec_parse" if i == 280 else "rec_put"],
            "inits": [],
        }
        for i in range(300)
    ]


def test_reach_credits_a_crash_in_case_280(tmp_path, monkeypatch):
    run = _run_dir(tmp_path, monkeypatch)
    hdir = _write_harness(
        run,
        "rec_parse(fuzz_buf, fuzz_len); rec_put(fuzz_buf, fuzz_len, 1);",
        reach_exempt={"rec_print": "debug output"},
        entry_style="dispatch",
        dispatch_case_count=300,
        dispatch_selector="identity16",
        api_cases=_wide_api_cases(),
    )
    harness_reach.record_exempt(hdir, "tools", None, "examples")
    assert harness_reach.main(["check", "--harness-dir", str(hdir)]) == 0
    _coverage(run, {"rec_parse": 0, "rec_put": 10})
    # Case 280 calls rec_parse, whose callee rec_check failed (no stack: the case path credits it).
    fdir = _write_fuzz_report(run, "api", [_art(run, _case_280() + b"\x00")])
    row = _reach_row(run, hdir, fdir)
    assert row["crashed_entry_points"] == ["rec_parse"], row
    # One selector byte only: the harness rejected the input, no case ran.
    fdir = _write_fuzz_report(run, "api", [_art(run, b"\x18")])
    assert _reach_row(run, hdir, fdir)["crashed_entry_points"] == []
    # Found under the one-byte selector at the same count: byte 0x18 meant case 24 then.
    fdir = _write_fuzz_report(run, "api", [_art(run, _case_280(), dispatch_selector="identity")])
    row = _reach_row(run, hdir, fdir)
    assert row["crashed_entry_points"] == []
    note = " ".join(row["crash_notes"])
    assert "(identity selector), case 24" in note and "(identity16 selector), case 280" in note, note


