def test_seeds_of_a_300_case_harness_carry_two_selector_bytes(tmp_path, monkeypatch):
    src = tmp_path / "buf.c"
    src.write_text("void take(const unsigned char *p, unsigned long n) { (void)p; (void)n; }\n", encoding="utf-8")
    names = [f"take_{i}" for i in range(300)]
    res = G.generate_module_harness(
        module_name="buf",
        sources=[str(src)],
        header_include=None,
        entry_fn="take",
        max_input_size=64,
        cppflags="",
        out_dir=tmp_path / "harnesses",
        entry_style="dispatch",
        dispatch_cases=[f"(void){fn}(fuzz_buf, fuzz_len);" for fn in names],
        auto_prelude=False,
    )
    harness = Path(res["harness_file"])
    sidecar = _sidecar(harness)
    harness_c = harness.read_text(encoding="utf-8")
    assert seed_harvest.selector_width(sidecar) == 2
    assert seed_harvest.selector_width(None, harness_c) == 2
    monkeypatch.chdir(tmp_path)
    calls = [{"fn": fn, "args": {"0": [["b", 0, "c0ffee"]]}} for fn in ("take_5", "take_280")]
    summary = seed_harvest.write_module("buf", sidecar, harness_c, calls, [])
    seeds = sorted(p.read_bytes() for p in (tmp_path / seed_harvest.SEEDS_DIR / "buf").iterdir())
    assert summary["seeds"] == 2
    assert seeds == sorted([b"\x05\x00\xc0\xff\xee", _case_280() + b"\xc0\xff\xee"])
    for seed in seeds:
        case = G.dispatch_case_of_bytes(seed, 300, G.dispatch_selector_of(sidecar))
        assert case is not None and f"take_{case}(" in dict(seed_harvest.harness_cases(harness_c))[case]


def test_api_seeds_and_imported_inputs_of_a_wide_harness_carry_two_selector_bytes(tmp_path, monkeypatch):
    monkeypatch.chdir(tmp_path)
    layout = {"selector": 280, "kind": "single", "calls": ["take"], "slots": [], "rest": {"call": 0, "param": 0}}
    assert seed_harvest.layout_seed(layout, [{"0": [["b", 0, "c0ffee"]]}], 2) == _case_280() + b"\xc0\xff\xee"
    sidecar = {"max_input_size": 100, "dispatch_selector": "identity16", "api_cases": [layout]}
    calls = [{"fn": "take", "args": {"0": [["b", 0, "c0ffee"]]}}]
    assert seed_harvest.write_layout_module("api", sidecar, calls, [])["seeds"] == 1
    [seed] = [p.read_bytes() for p in (tmp_path / seed_harvest.SEEDS_DIR / "api").iterdir()]
    assert seed == _case_280() + b"\xc0\xff\xee"

    # fuzz_assets: an imported corpus input goes behind the case's two selector bytes.
    corpus = tmp_path / fuzz_assets.CORPORA_DIR / "c1"
    corpus.mkdir(parents=True)
    (corpus / "in1").write_bytes(b"DATA")
    doc = {
        "corpora": [{"id": "c1", "imported": {}}],
        "fuzzers": [],
        "mappings": [{"corpus": "c1", "fuzzer": None, "functions": ["take"]}],
    }
    assert fuzz_assets._whole_input_selectors(sidecar, "", {"take"}) == [280]
    # Under a one-byte selector, 280 has no selector byte: never written behind a wrong one.
    assert fuzz_assets._whole_input_selectors({**sidecar, "dispatch_selector": "identity"}, "", {"take"}) == []
    report = fuzz_assets.write_module("api", sidecar, "", doc)
    assert report["inputs"] == 1, report
    [imported] = [p.read_bytes() for p in (tmp_path / fuzz_assets.IMPORTED_DIR / "api").iterdir()]
    assert imported == _case_280() + b"DATA"


