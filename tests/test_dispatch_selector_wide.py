"""
The two-byte dispatch selector (D7, S6b): above 256 cases the first two input bytes, little-endian,
are the case index (`identity16`); a harness with 256 cases or fewer is generated byte for byte as
before. Every reader (run_eacsl_fuzz, harness_reach) and writer (seed_harvest, fuzz_assets) of the
selector uses its width.
"""

