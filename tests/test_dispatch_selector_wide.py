def test_generated_wide_harness_runs_case_280(tmp_path):
    """
    Compiled and run: selector k < 300 runs case k (rc 0), anything else, or an input shorter than the
    two selector bytes, runs nothing (rc -1). Host cc, else Docker (skipped without FRAMAC_DOCKER_TESTS=1).
    """
    _gen(tmp_path, 300)
    driver = tmp_path / "driver.c"
    driver.write_text(
        '#include "harnesses/harness_mod.c"\n'
        "#include <stdio.h>\n"
        "static int last_hit = -1;\n"
        "int hit_case(unsigned int c) { last_hit = (int)c; return (int)c; }\n"
        "static void run(unsigned int c, size_t len) {\n"
        "    uint8_t in[3] = {(uint8_t)(c & 255U), (uint8_t)(c >> 8), 0x42U};\n"
        "    last_hit = -1;\n"
        "    int rc = LLVMFuzzerTestOneInput(in, len);\n"
        '    printf("case:%u:%u:%d:%d\\n", c, (unsigned int)len, rc, last_hit);\n'
        "}\n"
        "int main(void) {\n"
        "    unsigned int sels[] = {0U, 1U, 24U, 255U, 256U, 280U, 299U, 300U, 6424U, 65535U};\n"
        "    for (unsigned int i = 0; i < sizeof sels / sizeof sels[0]; i++) {\n"
        "        run(sels[i], 3U);\n"
        "    }\n"
        "    run(280U, 1U);\n"
        "    return 0;\n"
        "}\n",
        encoding="utf-8",
    )
    cc = shutil.which("clang") or shutil.which("gcc")
    if cc:
        exe = tmp_path / "wide_driver.exe"
        proc = subprocess.run(
            [cc, "-Wall", "-Werror", f"-I{tmp_path.as_posix()}", str(driver), "-o", str(exe)],
            capture_output=True,
            text=True,
            check=False,
        )
        assert proc.returncode == 0, proc.stderr
        stdout = subprocess.run([str(exe)], env=dict(os.environ), capture_output=True, text=True, check=True).stdout
    else:
        from conftest import ANALYSIS_IMAGE, require_docker_images

        require_docker_images(ANALYSIS_IMAGE)  # skips without FRAMAC_DOCKER_TESTS=1
        script = "cd /tmp && clang -Wall -Werror -I/fixture /fixture/driver.c -o drv && timeout 60 ./drv"
        argv = ["docker", "run", "--rm", "--network", "none", "-v", f"{tmp_path}:/fixture:ro", ANALYSIS_IMAGE, script]
        proc = subprocess.run(argv, capture_output=True, text=True, encoding="utf-8", errors="replace", timeout=300)
        assert proc.returncode == 0, proc.stdout[-2000:] + proc.stderr[-2000:]
        stdout = proc.stdout
    got = {}
    for ln in stdout.splitlines():
        if ln.startswith("case:"):
            _, c_s, len_s, rc_s, hit_s = ln.strip().split(":")
            got[(int(c_s), int(len_s))] = (int(rc_s), int(hit_s))
    assert len(got) == 11, stdout
    for (c, length), (rc, hit) in got.items():
        if length == 3 and c < 300:
            assert (rc, hit) == (0, c), (c, length, rc, hit)
        else:
            assert (rc, hit) == (-1, -1), (c, length, rc, hit)
