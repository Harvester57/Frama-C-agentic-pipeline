def _case_280() -> bytes:
    return bytes([280 & 255, 280 >> 8])


def _sidecar(harness: Path) -> dict:
    return json.loads(harness.with_suffix(".json").read_text(encoding="utf-8"))


def test_a_300_case_harness_selects_case_280_with_two_bytes(tmp_path):
    harness = _gen(tmp_path, 300)
    text = harness.read_text(encoding="utf-8")
    assert "switch (harness_selector) { /* dispatch selector: identity16, 300 cases */" in text
    assert "if (fuzz_len > 1) {" in text
    assert "uint16_t harness_selector = (uint16_t)(fuzz_buf[0] | (fuzz_buf[1] << 8));" in text
    assert "fuzz_buf += 2;" in text and "fuzz_len -= 2;" in text
    assert "uint8_t harness_selector" not in text
    assert "case 280U: { (void)hit_case(280U); } break;" in text
    assert "default: FRAMAC_FUZZ_REJECT(); break;" in text
    sidecar = _sidecar(harness)
    assert sidecar["dispatch_selector"] == "identity16" and sidecar["dispatch_case_count"] == 300
    assert "warnings" not in sidecar, sidecar.get("warnings")  # the schema allows identity16
    assert G.dispatch_selector_of_text(text) == ("identity16", 300)
    assert G.dispatch_selector_of(sidecar) == "identity16"
    assert G.dispatch_selector_width("identity16") == 2
    assert G.dispatch_case_of_bytes(_case_280(), 300, "identity16") == 280
    assert G.dispatch_case_of_bytes(_case_280() + b"rest", 300, "identity16") == 280
    assert G.dispatch_case_of_bytes(bytes([300 & 255, 300 >> 8]), 300, "identity16") is None
    assert G.dispatch_case_of_bytes(b"\x18", 300, "identity16") is None  # shorter than the selector
    assert G.dispatch_case_of_bytes(b"", 300, "identity16") is None
    assert G.dispatch_case_of_bytes(b"\x05\x00", 300, "identity16") == 5
    cases = dict(seed_harvest.harness_cases(text))
    assert len(cases) == 300 and cases[280].strip() == "(void)hit_case(280U);"
    # Every case keeps its Eva shard guard, so sharding still splits the 300 cases.
    assert eva_shards.harness_shardable(text)
    assert "#if !defined(FRAMAC_EVA_SHARD) || defined(FRAMAC_EVA_SHARD_CASE_299)" in text
    assert eva_shards.shard_cppflags([280, 299]) == [
        "-DFRAMAC_EVA_SHARD",
        "-DFRAMAC_EVA_SHARD_CASE_280",
        "-DFRAMAC_EVA_SHARD_CASE_299",
    ]


# sha256 of _build_dispatch_invocation's text at 0b0101e (before identity16), for `(void)hit_case(<i>U);`
# cases, without and with runtime_skip.
_NARROW_TEXT_SHA256 = {
    (3, False): "97959e59a306d7b5d38ef940579c3029ae25407341fa59c41569ddbca6bfe3dc",
    (3, True): "ef68de6431c0607cccba701350d869831c866b6ba1d19c0382941525591b8f52",
    (64, False): "0b7c58b874aa2be4b3fe34ba79806fb36f2893ccbd9cf4598c3d251098ef2f67",
    (64, True): "799145c4f0f97c04e4a99b970039789dcf452f03c39ce0ef17ddbf143ed8038a",
    (65, False): "0e0265f8dee38eb0ef074b4253793a01b63b9f2f4469170c21e87d61bbbaae92",
    (65, True): "ab86f497408646a4bb7addc4d93817eca439912787e11009b598ffa1f0419e74",
    (256, False): "8def3230181f7b1ef2c9c8f64d40063da0d7f1440b6be057c8e61009bcedab1b",
    (256, True): "6e03921ad4e0cc917dcf3e258c50e006df83691d35aa603bcbeed5e4ba2cc21c",
}


@pytest.mark.parametrize(("n", "runtime_skip"), sorted(_NARROW_TEXT_SHA256))
def test_a_256_case_harness_is_generated_as_before(n, runtime_skip):
    text = G._build_dispatch_invocation([f"(void)hit_case({i}U);" for i in range(n)], runtime_skip=runtime_skip)
    assert hashlib.sha256(text.encode("utf-8")).hexdigest() == _NARROW_TEXT_SHA256[(n, runtime_skip)]
    assert f"switch (harness_selector) {{ /* dispatch selector: identity, {n} cases */" in text
    assert "uint8_t harness_selector = fuzz_buf[0];" in text and "identity16" not in text


