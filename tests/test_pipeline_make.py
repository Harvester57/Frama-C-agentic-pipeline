def _target_fuzzer_run(run: Path) -> Path:
    """_unit_run plus tf_fuzz_kv, a target fuzz module of libkv_a around workspace/work/fuzz/fuzz_kv.c."""
    _unit_run(run)
    src = "workspace/work/fuzz/fuzz_kv.c"
