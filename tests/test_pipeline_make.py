class FakeScripts:
    def __init__(self, fail: set[str] | None = None):
        self.calls: list[tuple[str, list[str]]] = []
        self.fail = fail or set()

    def __call__(self, script, args):
        self.calls.append((script, list(args)))
        name = args[0]
        return (1 if name in self.fail else 0), json.dumps({"ok": name not in self.fail})


def _ledger_calls(fake: FakeScripts) -> list[tuple[str, list[str]]]:
    return [(args[0], args[1:]) for script, args in fake.calls if script == "ledger.py"]


