def test_mk_quote_escapes_make_and_shell():
    assert pm.mk_quote("plain/path.c") == "plain/path.c"
    assert pm.mk_quote("") == "''"
    assert pm.mk_quote("a b") == "'a b'"
    assert pm.mk_quote("-DQ=$5") == "'-DQ=$$5'"
    assert pm.mk_quote("a#b") == "'a\\#b'"
    # make halves a backslash run before `#`: k literal backslashes need 2k+1.
    assert pm.mk_quote("a\\#b") == "'a\\\\\\#b'"
    assert pm.mk_quote("x'y") == "'x'\"'\"'y'"
    with pytest.raises(ValueError):
        pm.mk_quote("a\nb")


