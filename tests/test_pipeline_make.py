class FakeMake:
    """Records make invocations; fails the given recipes the way GNU make 4.3 reports them."""

    def __init__(self, failing: dict[str, int] | None = None, writes: dict[str, str] | None = None):
        self.calls: list[list[str]] = []
        self.failing = failing or {}
        self.writes = writes or {}

    def __call__(self, cmd, cwd, sink):
        self.calls.append(cmd)
        for rel, text in self.writes.items():
            (cwd / rel).parent.mkdir(parents=True, exist_ok=True)
            (cwd / rel).write_text(text, encoding="utf-8")
        for target, code in self.failing.items():
            sink(f"make: *** [/opt/framac-pipeline/scripts/../templates/pipeline.mk:83: {target}] Error {code}")
        return 2 if self.failing else 0


